#!/usr/bin/env python3
"""A README.md in every script folder, generated from the scripts' own headers, so that the public release reads like a
repository (the author, 2 November 2026: "do all scripts have readmes + some images of how the app looks? similar to how we
do in github?"). For each folder it lists every script with the first sentence of its docstring and its usage line, and
says where the folder sits in the pipeline. Regenerated by scripts_map.py's step whenever a script changes.

Usage: python3 scripts/paper_ppml/folder_readmes.py
"""
import ast, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
FOLDERS = {
    'scripts/paper_ppml': ('The paper: records to counts, tables, figures, the build and its checks',
                           'Run from the workspace root in this order: `data.py`, `PPML_PARTS_NAME=parts-v<n> data_v68.py`, `experiment_v82.py`, then '
                           '`PPML_PARTS=… PPML_STUDIES=… build.py <n> --check` (or without `--check` to render the Word file), then the checks '
                           '(`verify_v68.py`, `check_claims_v68.py`, `style_check.py <n>`, `claims_audit.py`), the deck (`figures_pptx.py <n>`), the '
                           'supporting document, the IEEE Access renderings and `release_package.py <n>`. `Docs/SCRIPTS-MAP.html` maps each script to the part of the paper it serves.'),
    'scripts/review': ('Shared primitives: the figure drawing, the Word look, the author checks and the Review Viewer',
                       'Imported by the paper scripts (`figures_static.py` draws every SVG figure; `paper_look.py` gives the Word files and the viewer one look; '
                       '`annotate_author_checks.py` writes the copy with the author checks).'),
    'scripts/search_ppml': ('The recorded search: strings, merge of the exports, automated rules, the screening application',
                            'The strings live in `strings.py` and `strings_regulation.py`; the exports are merged and de-duplicated by `merge.py`; the screening '
                            'application serves the records to the reviewer; the second screening runs in batches. The database exports themselves are not '
                            'redistributed (see EXCLUSIONS.md of the release); `search-ppml/exports/PROVENANCE-*.tsv` holds their checksums.'),
    'scripts/paper': ('Earlier build steps still used by the paper build',
                      'Kept for the parts the current build imports (the comments part of the Word file, the PNG type fix).'),
    'scripts': ('All scripts of the review',
                'Subfolders: `paper_ppml/` (the paper), `review/` (shared primitives and the viewer), `search_ppml/` (the search), `paper/` (earlier build '
                'steps). The extraction and OCR pipeline sits at this level: `run_extraction.sh` runs extraction, OCR with Apple Vision and Tesseract, '
                '`verify_ocr.py` against the page renders, `sections.py` and `check_extraction.py`; `scripts/README.md` describes it.'),
}


def header(path):
    """the first sentence of the module docstring and its usage line"""
    try:
        doc = ast.get_docstring(ast.parse(path.read_text(encoding='utf-8', errors='ignore'))) or ''
    except SyntaxError:
        doc = ''
    if not doc and path.suffix == '.sh':
        lines = [l[1:].strip() for l in path.read_text(encoding='utf-8', errors='ignore').splitlines()[1:6] if l.startswith('#')]
        doc = ' '.join(lines)
    first = re.split(r'(?<=[.!?])\s', doc.strip().replace('\n', ' '), maxsplit=1)[0] if doc else '(no header)'
    usage = re.search(r'Usage:\s*(.+)', doc)
    return first.strip(), (usage.group(1).strip().split('\n')[0] if usage else '')


def main():
    for folder, (title, intro) in FOLDERS.items():
        d = ROOT / folder
        if not d.exists():
            continue
        scripts = sorted([p for p in d.iterdir() if p.suffix in ('.py', '.sh') and not p.name.startswith('.')], key=lambda p: p.name)
        if folder == 'scripts':
            scripts = [p for p in scripts]                              # the top level only; subfolders have their own README
        rows = []
        for p in scripts:
            first, usage = header(p)
            rows.append(f'| `{p.name}` | {first} | {("`" + usage + "`") if usage else ""} |')
        shots = sorted((d / 'docs').glob('*.png')) if (d / 'docs').exists() else []
        shot_md = ('\n\n## Screenshots\n\nTaken by `scripts/review/app_screenshot.py` on the real records; where a paper is shown it is Shawkat et al. 2025, published under CC BY 4.0.\n\n'
                   + ''.join(f'![{s.stem}](docs/{s.name})\n\n' for s in shots)) if shots else ''
        body = (f'# {title}\n\n{intro}\n\n| Script | Purpose | Usage |\n|---|---|---|\n' + '\n'.join(rows) + shot_md +
                '\n\nGenerated by `scripts/paper_ppml/folder_readmes.py` from each script\'s header; edit the headers, not this file.\n')
        out = d / 'README.md'
        if folder == 'scripts' and out.exists():                       # the extraction pipeline's own README stays; the table is appended under a heading
            existing = out.read_text(encoding='utf-8')
            marker = '\n## The scripts of this folder\n'
            existing = existing.split(marker)[0].rstrip() + '\n'
            out.write_text(existing + marker + '\n' + body.split('\n\n', 2)[2], encoding='utf-8')
        else:
            out.write_text(body, encoding='utf-8')
        print(f'{folder}/README.md: {len(rows)} scripts')


if __name__ == '__main__':
    main()
